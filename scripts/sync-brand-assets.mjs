import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const kit = resolve(root, "branding");
const check = process.argv.includes("--check");
const read = (path) => readFile(resolve(kit, path));
const runtime = JSON.parse(await read("exports/runtime.json"));
const source = JSON.parse(await read("source/brand.json"));
const marks = JSON.parse(await read("source/marks.json"));
if (JSON.stringify(runtime.colors) !== JSON.stringify(source.colors) || JSON.stringify(runtime.marks) !== JSON.stringify(marks)) {
  throw new Error("Brand kit masters changed. Rebuild branding before syncing application assets.");
}

const outputs = new Map();
outputs.set("lib/brand-assets.ts", Buffer.from(
  "// Generated by scripts/sync-brand-assets.mjs from the approved brand kit.\n" +
  `export const brandAssets = ${JSON.stringify(runtime, null, 2)} as const;\n`,
));
outputs.set("app/brand-tokens.css", Buffer.from(
  "/* Generated by scripts/sync-brand-assets.mjs from branding/source/brand.json. */\n:root {\n" +
  Object.entries(source.colors).map(([name, value]) => `  --brand-${name}: ${value};`).join("\n") + "\n}\n",
));

for (const brand of ["servio", "sable"]) {
  for (const name of ["favicon.svg", "icon-192.png", "icon-512.png", "maskable-512.png"]) {
    outputs.set(`public/brand/${brand}/${name}`, await read(`exports/${brand}/icons/${name}`));
  }
  const manifest = JSON.parse(await read(`exports/${brand}/icons/site.webmanifest`));
  manifest.icons = [
    { src: "icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
    { src: "icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
    { src: "maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  ];
  outputs.set(`public/brand/${brand}/site.webmanifest`, Buffer.from(JSON.stringify(manifest, null, 2) + "\n"));
}
for (const [destination, sourcePath] of [
  ["app/favicon.ico", "exports/servio/icons/favicon.ico"],
  ["app/icon.svg", "exports/servio/icons/favicon.svg"],
  ["app/apple-icon.png", "exports/servio/icons/apple-touch-icon.png"],
  ["app/opengraph-image.png", "exports/social/servio-og-dark.png"],
  ["app/twitter-image.png", "exports/social/servio-og-dark.png"],
  ["app/(console)/assistant/icon.svg", "exports/sable/icons/favicon.svg"],
]) outputs.set(destination, await read(sourcePath));

for (const [relative, bytes] of outputs) {
  const destination = resolve(root, relative);
  if (check) {
    let current;
    try { current = await readFile(destination); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (!current?.equals(bytes)) throw new Error(`Brand asset out of date: ${relative}. Run pnpm brand:sync.`);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, bytes);
  }
}
console.log(`${check ? "Verified" : "Synced"} ${outputs.size} application brand assets.`);
